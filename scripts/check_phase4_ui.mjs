import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
const b=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
const p=await b.newPage({viewport:{width:1200,height:900}});p.setDefaultTimeout(8000);const errors=[];p.on('pageerror',e=>errors.push(e.message));
await p.goto('http://127.0.0.1:5173/?view=content');
await p.getByRole('heading',{name:'Inspect a course bundle.'}).waitFor();
const file=p.getByLabel('Structured content JSON');
await file.setInputFiles('content/private/lesson8-sample.json');
await p.getByRole('heading',{name:'Structure accepted'}).waitFor();
await p.getByText('3 / 34 original items included. 31 not yet imported.').waitFor();
assert.equal(await p.locator('.content-entry').count(),3);
await p.getByText('8.1 / 1 · You (pl.) finish.',{exact:true}).click();
await p.getByText('Vous finissez.',{exact:true}).waitFor();
const raw=JSON.parse(await readFile('content/private/lesson8-sample.json','utf8'));
raw.exercises[0].answerKeyId='answer.missing';
await file.setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(raw))});
await p.getByRole('heading',{name:'Validation failed'}).waitFor();
await p.getByRole('alert').getByText('previously loaded content',{exact:false}).waitFor();
assert.equal(await p.locator('.content-entry').count(),3);
await file.setInputFiles({name:'malformed.json',mimeType:'application/json',buffer:Buffer.from('{')});
await p.getByRole('heading',{name:'Validation failed'}).waitFor();
await file.setInputFiles('content/private/lesson8-sample.json');
await p.getByRole('heading',{name:'Structure accepted'}).waitFor();
await p.setViewportSize({width:390,height:844});
assert(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await mkdir('artifacts/phase4',{recursive:true});await p.screenshot({path:'artifacts/phase4/content-inspector-mobile.png',fullPage:true});
assert.deepEqual(errors,[]);await b.close();
console.log('PASS: valid content renders, coverage visible, answer resolves, invalid JSON/reference rejected, last valid bundle preserved, mobile no overflow, no JS exceptions.');
